from random import choice, shuffle

from lab1.task2.retry import retry


@retry(5, 1, [ZeroDivisionError])
def my_func() -> int:
    """
    Демонстрационная функция для тестирования декоратора retry.

    Функция создает список из 140 элементов: 100 нулей и 40 единиц,
    перемешивает их случайным образом, затем выбирает случайный элемент
    и выполняет целочисленное деление 10 на выбранное значение.

    Returns:
        int: Результат целочисленного деления 10 на случайно выбранное число

    Raises:
        ZeroDivisionError: Возникает, когда из списка выбрано значение 0.
    """
    integers = [0] * 100 + [1] * 40
    shuffle(integers)
    return 10 // choice(integers)


if __name__ == '__main__':
    """
    Точка входа в программу.

    Запускает функцию my_func, которая благодаря декоратору retry
    будет автоматически повторять выполнение при возникновении ZeroDivisionError.
    """
    my_func()