from datetime import datetime


def current_time():
    """
    Возвращает текущее время в отформатированном строковом представлении.

    Функция получает текущее системное время и форматирует его в строку
    с точностью до миллисекунд (3 знака после запятой).

    Returns:
        str: Текущее время в формате "ЧЧ:ММ:СС.ммм"
             где ЧЧ - часы (00-23), ММ - минуты (00-59),
             СС - секунды (00-59), ммм - миллисекунды (000-999)
    """
    return datetime.now().strftime("%H:%M:%S.%f")[:-3]