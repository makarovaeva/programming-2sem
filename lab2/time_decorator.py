import asyncio
import time
from typing import Callable, Any


def time_decorator(func: Callable) -> Callable:
    """
    Декоратор для измерения времени выполнения синхронных и асинхронных функций.

    Универсальный декоратор, который автоматически определяет тип функции
    (синхронная или асинхронная) и возвращает соответствующую обертку.
    Измеряет время выполнения функции и возвращает кортеж из времени
    выполнения и результата исходной функции.

    Args:
        func (Callable): Декорируемая функция (может быть как синхронной,
                        так и асинхронной)

    Returns:
        Callable: Функция-обертка, которая возвращает кортеж
                 (время_выполнения: float, результат: Any)
    """

    async def async_wrapper(*args, **kwargs) -> tuple[float, Any]:
        """
        Асинхронная обертка для декорирования асинхронных функций.

        Измеряет время выполнения асинхронной функции, вызывая её с помощью await.
        Возвращает кортеж из времени выполнения и результата функции.

        Args:
            *args: Позиционные аргументы для декорируемой функции
            **kwargs: Именованные аргументы для декорируемой функции

        Returns:
            tuple[float, Any]: Кортеж, где первый элемент - время выполнения
                              в секундах, второй - результат функции
        """
        t_start = time.time()
        res = await func(*args, **kwargs)
        return time.time() - t_start, res

    def wrapper(*args, **kwargs) -> tuple[float, Any]:
        """
        Синхронная обертка для декорирования синхронных функций.

        Измеряет время выполнения синхронной функции.
        Возвращает кортеж из времени выполнения и результата функции.

        Args:
            *args: Позиционные аргументы для декорируемой функции
            **kwargs: Именованные аргументы для декорируемой функции

        Returns:
            tuple[float, Any]: Кортеж, где первый элемент - время выполнения
                              в секундах, второй - результат функции
        """
        t_start = time.time()
        res = func(*args, **kwargs)
        return time.time() - t_start, res

    if asyncio.iscoroutinefunction(func):
        return async_wrapper
    return wrapper
